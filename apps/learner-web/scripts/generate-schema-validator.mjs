// Generates a CSP-safe standalone validator from the normative topic-pack schema.
// The generated TypeScript is committed and checked for drift in CI.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(scriptDir, "../../../content/schema/topic-pack.schema.json");
const outputPath = resolve(
  scriptDir,
  "../src/content/generated/topicPackSchemaValidator.ts",
);
const checkOnly = process.argv.includes("--check");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const ajv = new Ajv2020({
  strict: true,
  allErrors: true,
  code: { source: true, esm: true },
});
const validate = ajv.compile(schema);
const standalone = standaloneCode(ajv, validate)
  .replaceAll(
    'require("ajv/dist/runtime/ucs2length").default',
    "schemaStringLength",
  )
  .replaceAll('require("ajv/dist/runtime/equal").default', "schemaValuesEqual");

if (standalone.includes("require(")) {
  throw new Error("generated validator contains an unsupported runtime require");
}

const source = [
  "/* eslint-disable */",
  "// @ts-nocheck",
  "// Generated by scripts/generate-schema-validator.mjs. Do not edit manually.",
  "function schemaStringLength(value) { return [...value].length; }",
  `function schemaValuesEqual(left, right) {
  if (left === right) return true;
  if (!left || !right || typeof left !== "object" || typeof right !== "object") return false;
  if (Array.isArray(left) !== Array.isArray(right)) return false;
  const leftKeys = Object.keys(left);
  const rightKeys = Object.keys(right);
  if (leftKeys.length !== rightKeys.length) return false;
  return leftKeys.every((key) => Object.prototype.hasOwnProperty.call(right, key)
    && schemaValuesEqual(left[key], right[key]));
}`,
  standalone,
  "",
].join("\n");

if (checkOnly) {
  let current = "";
  try {
    current = readFileSync(outputPath, "utf8");
  } catch {
    // A missing generated file is reported as drift below.
  }
  if (current !== source) {
    console.error("generated topic-pack validator is missing or stale; run pnpm schema:generate");
    process.exit(2);
  }
  console.error("generated topic-pack validator is current");
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, source, "utf8");
  console.error("generated topic-pack validator updated");
}
